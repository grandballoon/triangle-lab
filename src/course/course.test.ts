// The course catalogue, read from the lessons themselves: the standalone
// pages' directions and every lab lesson built against a real Scene. It is
// written to catalogue.generated.ts as a file snapshot, so this fails while
// the file is out of date, and `npx vitest run src/course -u` writes it.

import { describe, expect, it } from "vitest";
import { directions } from "../directions.ts";
import { Scene, type LessonBuilder } from "../lab/scene.ts";
import { chapters } from "../lessons.ts";
import { course, courseLesson, courseStep, stepPlace, type CourseLesson } from "./course.ts";

const modules = import.meta.glob<{ default: LessonBuilder }>("../lab/lessons/*.ts", { eager: true });

function read(): CourseLesson[] {
  return chapters.flatMap((chapter) =>
    chapter.lessons.map((lesson) => {
      const steps = lesson.lab
        ? modules[`../lab/lessons/${lesson.slug}.ts`]!.default(new Scene(lesson.accent)).steps
        : (directions[lesson.slug] ?? []);
      return {
        slug: lesson.slug,
        chapter: chapter.title,
        name: lesson.name,
        steps: steps.map(({ title, text }) => ({ title, text })),
      };
    }),
  );
}

const HEADER = `// Generated by course.test.ts from the lessons: do not edit. Run
// \`npx vitest run src/course -u\` to write it again after changing a lesson.

import type { CourseLesson } from "./course.ts";

export const catalogue: CourseLesson[] = `;

describe("the course catalogue", () => {
  it("holds every lesson's steps as the lessons have them", async () => {
    await expect(`${HEADER}${JSON.stringify(read(), null, 2)};\n`).toMatchFileSnapshot("./catalogue.generated.ts");
  });

  it("is what course.ts reads", () => {
    expect(course).toEqual(read());
    expect(course.every((l) => l.steps.length > 0)).toBe(true);
  });

  it("finds a lesson and a step, and says where a step is", () => {
    const medians = courseLesson("medians")!;
    expect(medians).toMatchObject({ chapter: "Triangles", name: expect.any(String) });
    expect(courseStep("medians", 0)).toEqual(medians.steps[0]);
    expect(courseStep("medians", 99)).toBeNull();
    expect(courseLesson("nowhere")).toBeNull();
    expect(stepPlace(medians, 0)).toBe(`Triangles · ${medians.name} · Step 1: ${medians.steps[0].title}`);
  });
});
